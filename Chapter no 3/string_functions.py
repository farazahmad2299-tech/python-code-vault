# len()  fuction is used to find the lenght of string
name = "faraz"
Length = len(name)
print(Length)

# .endswith() fuction is used to check wether a particular
# character is exists in a string or Not.
End_with = name.endswith("az")
print(End_with)

# .count() fuction is used to check how many times a particular
# character is come in a string.
Count_Functin = name.count("a")
print(Count_Functin)


# .capitalize() function is used to capitazed the first index
# of a string.
Capitalize_Function = name.capitalize()
print(Capitalize_Function)

# .find() function is used to find a character a it gives 
# the index of the character you find in the output.
Find = name.find("r")
print(Find)


# .replace function replace a whole string with anoter or 
# replace a character with other 
Replace = name.replace("f","S")
print(Replace)